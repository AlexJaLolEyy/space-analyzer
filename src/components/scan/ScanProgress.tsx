import { motion, AnimatePresence } from "framer-motion";
import { Loader2, XCircle, Search, Database } from "lucide-react";
import { useState, useEffect, useMemo } from "react";
import type { ScanProgress as ProgressType } from "../../types/scan";
import { ScanStats } from "./ScanStats";

interface ScanProgressProps {
    progress: ProgressType | null;
    path: string;
    onCancel: () => void;
}

const FUN_FACTS = [
    "Did you know? The average PC has 47GB of duplicate files.",
    "Emptying the recycle bin regularly can save gigabytes of space.",
    "Browser cache can easily grow to over 5GB if not cleared.",
    "Uninstalling unused large games is the fastest way to regain space.",
    "Temporary files are generated by apps but rarely cleaned up automatically.",
];

/** Turbo-Mode lines embed "Phase 1" … "Phase 4"; standard walker sends raw directory paths. */
function parseTurboPhase(currentPath: string): 1 | 2 | 3 | 4 | null {
    if (/Reading file table|Scanning folders/i.test(currentPath)) return 3;
    if (/Building index/i.test(currentPath)) return 4;
    return null;
}

export function ScanProgress({ progress, path, onCancel }: ScanProgressProps) {
    const rootName = path.replace(/[/\\]$/, "").split(/[/\\]/).pop() || path;
    const [factIndex, setFactIndex] = useState(0);

    useEffect(() => {
        const interval = setInterval(() => {
            setFactIndex(i => (i + 1) % FUN_FACTS.length);
        }, 4000);
        return () => clearInterval(interval);
    }, []);

    const turboPhase = progress ? parseTurboPhase(progress.current_path) : null;
    const phaseBucket = useMemo(() => {
        if (turboPhase !== null) return turboPhase;
        if (!progress) return 1 as const;
        const p = progress.current_path;
        if (p.includes("Starting scan")) return 1 as const;
        if (progress.bytes_scanned > 0) return 3 as const;
        return 2 as const;
    }, [progress, turboPhase]);

    const phaseText =
        progress && progress.current_path.trim() !== ""
            ? progress.current_path
            : phaseBucket === 1
              ? "Indexing file system…"
              : "Calculating sizes…";

    const currentFact = FUN_FACTS[factIndex];
    const determinatePct =
        progress && progress.percent > 0 ? Math.min(100, progress.percent) : 0;
    const showDeterminate = determinatePct > 0;

    const getPhaseIcon = () => {
        if (phaseBucket === 1) return <Search className="w-9 h-9 text-blue-500/60" />;
        if (phaseBucket === 2) return <Search className="w-9 h-9 text-blue-500/60" />;
        if (phaseBucket === 3) return <Database className="w-9 h-9 text-green-500/60" />;
        return <Loader2 className="w-9 h-9 text-purple-500/60 animate-spin" />;
    };

    const getPhaseColor = () => {
        if (phaseBucket === 3) return "text-green-500";
        if (phaseBucket === 4) return "text-purple-500";
        return "text-blue-500";
    };

    const getPhaseBg = () => {
        if (phaseBucket === 3) return "bg-green-500/10";
        if (phaseBucket === 4) return "bg-purple-500/10";
        return "bg-blue-500/10";
    };

    const barTint =
        phaseBucket === 3 ? "#22c55e" : phaseBucket === 4 ? "#a855f7" : "#3b82f6";

    return (
        <motion.div
            initial={{ opacity: 0, scale: 0.97 }}
            animate={{ opacity: 1, scale: 1 }}
            exit={{ opacity: 0, scale: 0.95 }}
            transition={{ duration: 0.3 }}
            className="flex-1 flex flex-col items-center justify-center p-8 w-full max-w-4xl mx-auto"
        >
            <div className="relative mb-8 flex flex-col items-center gap-4 min-h-48">
                <AnimatePresence mode="wait">
                    <motion.div
                        key={phaseText}
                        initial={{ opacity: 0, y: 10 }}
                        animate={{ opacity: 1, y: 0 }}
                        exit={{ opacity: 0, y: -10 }}
                        transition={{ duration: 0.4 }}
                        className="flex flex-col items-center"
                    >
                        <div className="relative mb-4">
                            <div className={`w-20 h-20 rounded-full ${getPhaseBg()} flex items-center justify-center`}>
                                {getPhaseIcon()}
                            </div>
                            <motion.div
                                className={`absolute inset-0 rounded-full border-2 ${getPhaseColor().replace("text-", "border-")}/30`}
                                animate={{ scale: [1, 1.4, 1.4], opacity: [0.5, 0, 0] }}
                                transition={{ repeat: Infinity, duration: 2, ease: "easeOut" }}
                            />
                        </div>
                        <h2 className={`text-2xl font-bold tracking-tight ${getPhaseColor()} text-center`}>
                            {phaseText}
                        </h2>
                        {progress?.engine && (
                            <span className="mt-2 px-2 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider bg-secondary text-muted-foreground">
                                {progress.engine}
                            </span>
                        )}
                        <p className="text-sm font-medium text-muted-foreground mt-1 text-center">
                            Scanning <span className="text-foreground">{rootName}</span>
                        </p>
                        {showDeterminate && (
                            <p className="text-xs text-muted-foreground tabular-nums mt-1">
                                {determinatePct.toFixed(1)}% complete
                            </p>
                        )}
                    </motion.div>
                </AnimatePresence>
            </div>

            <div
                className="w-full max-w-3xl glass p-8 rounded-2xl relative overflow-hidden transition-colors duration-500"
                style={{
                    borderColor:
                        phaseBucket === 3
                            ? "rgba(34,197,94,0.1)"
                            : phaseBucket === 4
                              ? "rgba(168,85,247,0.12)"
                              : "rgba(59,130,246,0.1)",
                }}
            >
                <div className="absolute top-0 left-0 w-full h-0.5 bg-secondary overflow-hidden">
                    {showDeterminate ? (
                        <motion.div
                            className="absolute left-0 top-0 h-full rounded-sm"
                            initial={false}
                            animate={{
                                width: `${determinatePct}%`,
                                background: `linear-gradient(90deg, ${barTint}99, ${barTint})`,
                            }}
                            transition={{ type: "tween", duration: 0.35, ease: "easeOut" }}
                        />
                    ) : (
                        <motion.div
                            className="absolute h-full"
                            style={{
                                width: "40%",
                                background: `linear-gradient(to right, transparent, ${barTint}, transparent)`,
                            }}
                            animate={{ left: ["-40%", "140%"] }}
                            transition={{ repeat: Infinity, duration: 1.8, ease: "linear" }}
                        />
                    )}
                </div>

                {progress ? (
                    <ScanStats progress={progress} />
                ) : (
                    <div className="h-32 flex flex-col items-center justify-center gap-3">
                        <Loader2 className="w-8 h-8 text-primary/60 animate-spin" />
                        <p className="text-muted-foreground text-sm text-center max-w-sm">
                            Connecting to the scanner — file and byte counts will update as the disk is read.
                        </p>
                    </div>
                )}

                <div className="mt-8 pt-6 border-t border-border/50 text-center">
                    <div className="h-6">
                        <AnimatePresence mode="wait">
                            <motion.p
                                key={factIndex}
                                initial={{ opacity: 0, y: 5 }}
                                animate={{ opacity: 1, y: 0 }}
                                exit={{ opacity: 0, y: -5 }}
                                className="text-sm font-medium text-muted-foreground italic"
                            >
                                {currentFact}
                            </motion.p>
                        </AnimatePresence>
                    </div>
                </div>
            </div>

            <motion.button
                whileHover={{ scale: 1.03 }}
                whileTap={{ scale: 0.97 }}
                onClick={onCancel}
                className="mt-8 flex items-center gap-2 px-6 py-3 rounded-xl bg-destructive/10 text-destructive hover:bg-destructive hover:text-destructive-foreground transition-colors font-medium"
            >
                <XCircle size={18} />
                Cancel Scan
            </motion.button>
        </motion.div>
    );
}
